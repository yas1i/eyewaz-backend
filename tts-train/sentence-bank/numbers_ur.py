def words(n):
    """Spell a non-negative integer in Urdu words (Pakistani count: lakh/crore)."""
    if n <= 100:
        return UNITS_0_100[n]
    parts = []
    crore, n = divmod(n, 10_000_000)
    lakh, n = divmod(n, 100_000)
    thousand, n = divmod(n, 1_000)
    hundred, n = divmod(n, 100)
    if crore:
        parts.append(words(crore) + " کروڑ")
    if lakh:
        parts.append(words(lakh) + " لاکھ")
    if thousand:
        parts.append(words(thousand) + " ہزار")
    if hundred:
        parts.append(UNITS_0_100[hundred] + " سو")
    if n:
        parts.append(UNITS_0_100[n])
    return " ".join(parts)

